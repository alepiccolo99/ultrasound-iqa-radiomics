"""Reference-grouped nested model development for full-reference ultrasound IQA.

The default invocation reproduces the study's grouped nested validation from the
exact public derived data stored under ``data/paper``. A separate ``custom``
mode applies the same grouped nested model-development protocol to a
``radiomic_dataset.mat`` generated by ``matlab/prepare_radiomic_dataset.m``
plus a CSV containing one subjective target per test sample.

Scientific protocol retained from the study:
- leave-one-reference-group-out outer evaluation;
- leave-one-training-reference-group-out inner model selection;
- six full-reference radiomic representations;
- training-only zero-variance filtering, z-scoring, deterministic Spearman
  redundancy filtering, and LASSO feature selection;
- five regression families and the prespecified hyperparameter grid;
- pooled inner RMSE as the primary selection criterion, followed by MAE,
  R2, and deterministic candidate order as tie-breakers.

The held-out reference group is never used to fit a representation,
preprocessing transform, feature selector, model, or hyperparameter choice.
"""

