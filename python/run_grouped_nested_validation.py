@dataclass
class RepresentationFit:
    name: str
    shift: Optional[np.ndarray] = None
    margin: Optional[np.ndarray] = None


def representation_feature_names(rep: str, base_names: Sequence[str]) -> List[str]:
    base_names = list(base_names)
    if rep in {"signedDelta", "absoluteDelta", "normalizedDelta", "stableLogRatio"}:
        return [f"{rep}__{name}" for name in base_names]
    if rep == "jointRefTest":
        return [f"ref__{name}" for name in base_names] + [f"test__{name}" for name in base_names]
    if rep == "jointRefTestDelta":
        return (
            [f"ref__{name}" for name in base_names]
            + [f"test__{name}" for name in base_names]
            + [f"delta__{name}" for name in base_names]
        )
    raise ValueError(f"Unknown representation: {rep}")


def fit_representation(rep: str, X_ref_train: np.ndarray, X_test_train: np.ndarray) -> RepresentationFit:
    if rep != "stableLogRatio":
        return RepresentationFit(name=rep)

    both = np.vstack([X_ref_train, X_test_train])
    min_train = np.min(both, axis=0)
    q25 = np.percentile(both, 25, axis=0)
    q75 = np.percentile(both, 75, axis=0)
    iqr = q75 - q25
    median_abs = np.median(np.abs(both), axis=0)

    scale = np.maximum.reduce([iqr, median_abs, np.ones_like(iqr)])
    margin = 1e-6 * scale
    shift = np.maximum(0.0, -min_train) + margin

    return RepresentationFit(name=rep, shift=shift, margin=margin)


def apply_representation(
    fit: RepresentationFit,
    X_ref: np.ndarray,
    X_test: np.ndarray,
) -> np.ndarray:
    rep = fit.name

    if rep == "signedDelta":
        return X_ref - X_test

    if rep == "absoluteDelta":
        return np.abs(X_ref - X_test)

    if rep == "normalizedDelta":
        denominator = np.abs(X_ref) + np.abs(X_test)
        out = np.zeros_like(denominator, dtype=float)
        nonzero = denominator != 0
        out[nonzero] = (X_ref[nonzero] - X_test[nonzero]) / denominator[nonzero]
        return out

    if rep == "stableLogRatio":
        if fit.shift is None or fit.margin is None:
            raise RuntimeError("stableLogRatio was applied before fitting its training parameters.")
        ref_stable = np.maximum(X_ref + fit.shift, fit.margin)
        test_stable = np.maximum(X_test + fit.shift, fit.margin)
        return np.log(ref_stable) - np.log(test_stable)

    if rep == "jointRefTest":
        return np.hstack([X_ref, X_test])

    if rep == "jointRefTestDelta":
        return np.hstack([X_ref, X_test, X_ref - X_test])

    raise ValueError(f"Unknown representation: {rep}")


