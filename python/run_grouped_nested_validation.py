def params_json(values: Dict[str, Any]) -> str:
    return json.dumps(values, sort_keys=True, separators=(",", ":"))


def safe_corr(y_true: np.ndarray, y_pred: np.ndarray, kind: str) -> float:
    y_true = np.asarray(y_true, dtype=float).ravel()
    y_pred = np.asarray(y_pred, dtype=float).ravel()

    if np.std(y_true) == 0 or np.std(y_pred) == 0:
        return np.nan

    if kind == "pearson":
        return float(pearsonr(y_true, y_pred).statistic)
    if kind == "spearman":
        return float(spearmanr(y_true, y_pred).statistic)
    raise ValueError(kind)


def regression_metrics(y_true: np.ndarray, y_pred: np.ndarray) -> Dict[str, float]:
    y_true = np.asarray(y_true, dtype=float).ravel()
    y_pred = np.asarray(y_pred, dtype=float).ravel()

    residual = y_true - y_pred
    mse = float(np.mean(residual**2))
    rmse = float(np.sqrt(mse))
    mae = float(np.mean(np.abs(residual)))

    ss_res = float(np.sum(residual**2))
    ss_tot = float(np.sum((y_true - np.mean(y_true))**2))
    r2 = np.nan if ss_tot == 0 else 1.0 - ss_res / ss_tot

    return {
        "MAE": mae,
        "MSE": mse,
        "RMSE": rmse,
        "R2": float(r2),
        "PLCC": safe_corr(y_true, y_pred, "pearson"),
        "SROCC": safe_corr(y_true, y_pred, "spearman"),
    }


def deterministic_seed(outer_index: int, inner_index: int, model_index: int) -> int:
    return int(MASTER_SEED + outer_index * 100_000 + inner_index * 1_000 + model_index)


