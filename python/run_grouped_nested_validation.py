def run_inner_search(
    outer_index: int,
    outer_train_idx: np.ndarray,
    X_ref: np.ndarray,
    X_test: np.ndarray,
    y: np.ndarray,
    group_index: np.ndarray,
    base_feature_names: List[str],
) -> Dict[str, Any]:
    outer_train_idx = np.asarray(outer_train_idx, dtype=int)
    train_groups = sorted(np.unique(group_index[outer_train_idx]).astype(int).tolist())
    n_inner_folds = len(train_groups)

    if n_inner_folds < 2:
        raise ValueError("At least two training reference groups are required for inner grouped validation.")

    global_to_local = {int(gidx): i for i, gidx in enumerate(outer_train_idx.tolist())}
    n_outer_train = len(outer_train_idx)

    all_rows: List[Dict[str, Any]] = []
    candidate_order_counter = 0

    for rep in REPRESENTATIONS:
        rep_names = representation_feature_names(rep, base_feature_names)

        pred_store: Dict[Tuple[int, int], np.ndarray] = {}
        valid_store: Dict[Tuple[int, int], bool] = {}
        selected_counts_store: Dict[Tuple[int, int], List[int]] = {}

        for li in range(len(LASSO_ALPHAS)):
            for mi in range(len(MODEL_CONFIGS)):
                key = (li, mi)
                pred_store[key] = np.full(n_outer_train, np.nan, dtype=float)
                valid_store[key] = True
                selected_counts_store[key] = []

        for inner_number, held_inner_group in enumerate(train_groups, start=1):
            inner_val_global = outer_train_idx[group_index[outer_train_idx] == held_inner_group]
            inner_train_global = outer_train_idx[group_index[outer_train_idx] != held_inner_group]

            if len(inner_train_global) == 0 or len(inner_val_global) == 0:
                raise RuntimeError("Invalid grouped inner split.")

            rep_fit = fit_representation(rep, X_ref[inner_train_global], X_test[inner_train_global])
            Xtr_rep = apply_representation(rep_fit, X_ref[inner_train_global], X_test[inner_train_global])
            Xva_rep = apply_representation(rep_fit, X_ref[inner_val_global], X_test[inner_val_global])

            prep, Xtr_pre = fit_preprocessor(Xtr_rep, rep_names)
            Xva_pre = apply_preprocessor(prep, Xva_rep)

            val_local_positions = np.asarray(
                [global_to_local[int(g)] for g in inner_val_global],
                dtype=int,
            )
            ytr = y[inner_train_global]

            for li, lasso_alpha in enumerate(LASSO_ALPHAS):
                selected = fit_lasso_selector(Xtr_pre, ytr, lasso_alpha)
                if selected.size == 0:
                    for mi in range(len(MODEL_CONFIGS)):
                        valid_store[(li, mi)] = False
                    continue

                Xtr_sel = Xtr_pre[:, selected]
                Xva_sel = Xva_pre[:, selected]

                for mi, model_cfg in enumerate(MODEL_CONFIGS):
                    key = (li, mi)
                    if not valid_store[key]:
                        continue

                    seed = deterministic_seed(outer_index, inner_number, mi)
                    model = make_model(model_cfg, seed)

                    try:
                        with warnings.catch_warnings():
                            warnings.simplefilter("ignore")
                            model.fit(Xtr_sel, ytr)
                            pred = np.asarray(model.predict(Xva_sel), dtype=float).ravel()

                        if pred.shape[0] != len(inner_val_global) or not np.all(np.isfinite(pred)):
                            valid_store[key] = False
                            continue

                        pred_store[key][val_local_positions] = pred
                        selected_counts_store[key].append(int(selected.size))
                    except Exception:
                        valid_store[key] = False

        y_outer_train = y[outer_train_idx]

        for li, lasso_alpha in enumerate(LASSO_ALPHAS):
            for mi, model_cfg in enumerate(MODEL_CONFIGS):
                candidate_order_counter += 1
                key = (li, mi)
                preds = pred_store[key]

                valid = (
                    valid_store[key]
                    and np.all(np.isfinite(preds))
                    and len(selected_counts_store[key]) == n_inner_folds
                )

                row: Dict[str, Any] = {
                    "CandidateOrder": candidate_order_counter,
                    "Representation": rep,
                    "LassoAlpha": lasso_alpha,
                    "ModelFamily": model_cfg["family"],
                    "ModelParamsJSON": params_json(model_cfg["params"]),
                    "Valid": bool(valid),
                }

                if valid:
                    metrics = regression_metrics(y_outer_train, preds)
                    row.update({
                        "InnerMAE": metrics["MAE"],
                        "InnerRMSE": metrics["RMSE"],
                        "InnerR2": metrics["R2"],
                    })
                else:
                    row.update({"InnerMAE": np.nan, "InnerRMSE": np.nan, "InnerR2": np.nan})

                all_rows.append(row)

    leaderboard = pd.DataFrame(all_rows)
    valid_lb = leaderboard[leaderboard["Valid"]].copy()
    if valid_lb.empty:
        raise RuntimeError(f"Outer fold {outer_index}: no valid inner candidate.")

    valid_lb["_sort_r2"] = -valid_lb["InnerR2"]
    valid_lb = valid_lb.sort_values(
        by=["InnerRMSE", "InnerMAE", "_sort_r2", "CandidateOrder"],
        ascending=[True, True, True, True],
        kind="mergesort",
    )
    return valid_lb.iloc[0].drop(labels=["_sort_r2"]).to_dict()


def fit_predict_outer(
    outer_index: int,
    best: Dict[str, Any],
    train_idx: np.ndarray,
    test_idx: np.ndarray,
    X_ref: np.ndarray,
    X_test: np.ndarray,
    y: np.ndarray,
    base_feature_names: List[str],
) -> Tuple[np.ndarray, List[str]]:
    rep = str(best["Representation"])
    lasso_alpha = float(best["LassoAlpha"])
    family = str(best["ModelFamily"])
    model_params = json.loads(str(best["ModelParamsJSON"]))

    rep_names = representation_feature_names(rep, base_feature_names)
    rep_fit = fit_representation(rep, X_ref[train_idx], X_test[train_idx])
    Xtr_rep = apply_representation(rep_fit, X_ref[train_idx], X_test[train_idx])
    Xte_rep = apply_representation(rep_fit, X_ref[test_idx], X_test[test_idx])

    prep, Xtr_pre = fit_preprocessor(Xtr_rep, rep_names)
    Xte_pre = apply_preprocessor(prep, Xte_rep)

    selected = fit_lasso_selector(Xtr_pre, y[train_idx], lasso_alpha)
    if selected.size == 0:
        raise RuntimeError(
            f"Outer fold {outer_index}: selected candidate retains zero features after outer refit."
        )

    matching_model_index = None
    selected_cfg = None
    for mi, cfg in enumerate(MODEL_CONFIGS):
        if cfg["family"] == family and params_json(cfg["params"]) == params_json(model_params):
            matching_model_index = mi
            selected_cfg = cfg
            break

    if selected_cfg is None or matching_model_index is None:
        raise RuntimeError("Could not recover selected model configuration.")

    seed = deterministic_seed(outer_index, 99, matching_model_index)
    model = make_model(selected_cfg, seed)

    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        model.fit(Xtr_pre[:, selected], y[train_idx])
        pred = np.asarray(model.predict(Xte_pre[:, selected]), dtype=float).ravel()

    if pred.shape[0] != len(test_idx) or not np.all(np.isfinite(pred)):
        raise RuntimeError(f"Outer fold {outer_index}: invalid outer predictions.")

    preprocessed_names = names_after_preprocessor(prep)
    selected_names = [preprocessed_names[i] for i in selected]
    return pred, selected_names


