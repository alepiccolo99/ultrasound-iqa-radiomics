def fit_lasso_selector(X_train: np.ndarray, y_train: np.ndarray, alpha: float) -> np.ndarray:
    with warnings.catch_warnings():
        warnings.simplefilter("ignore", category=ConvergenceWarning)
        selector = Lasso(
            alpha=float(alpha),
            fit_intercept=True,
            max_iter=100_000,
            tol=1e-7,
            selection="cyclic",
        )
        selector.fit(X_train, y_train)
    return np.flatnonzero(selector.coef_ != 0.0)


def make_model(config: Dict[str, Any], random_state: int):
    family = config["family"]
    p = dict(config["params"])

    if family == "MLR":
        return LinearRegression()
    if family == "Ridge":
        return Ridge(alpha=float(p["alpha"]))
    if family == "DecisionTree":
        return DecisionTreeRegressor(
            max_depth=int(p["max_depth"]),
            min_samples_split=int(p["min_samples_split"]),
            min_samples_leaf=int(p["min_samples_leaf"]),
            random_state=random_state,
        )
    if family == "GradientBoosting":
        return GradientBoostingRegressor(
            n_estimators=int(p["n_estimators"]),
            learning_rate=float(p["learning_rate"]),
            max_depth=int(p["max_depth"]),
            random_state=random_state,
            loss="squared_error",
        )
    if family == "RBF_SVR":
        return SVR(kernel="rbf", C=float(p["C"]), gamma=float(p["gamma"]))

    raise ValueError(f"Unknown model family: {family}")


