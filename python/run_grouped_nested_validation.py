@dataclass
class Preprocessor:
    keep_nonconstant: np.ndarray
    mean_: np.ndarray
    std_: np.ndarray
    keep_spearman: np.ndarray
    input_feature_names: List[str]


def greedy_spearman_keep(X_train_z: np.ndarray, threshold: float) -> np.ndarray:
    n_features = X_train_z.shape[1]
    if n_features == 1:
        return np.array([0], dtype=int)

    ranks = rankdata(X_train_z, axis=0, method="average")
    rank_std = np.std(ranks, axis=0, ddof=0)
    valid = np.where(np.isfinite(rank_std) & (rank_std > 0))[0]

    if valid.size == 0:
        raise ValueError("All features became rank-degenerate before Spearman filtering.")
    if valid.size == 1:
        return valid.astype(int)

    R = ranks[:, valid]
    R_mean = np.mean(R, axis=0)
    R_std = np.std(R, axis=0, ddof=0)
    Z = (R - R_mean) / R_std
    corr = (Z.T @ Z) / Z.shape[0]
    corr = np.clip(corr, -1.0, 1.0)

    kept_local: List[int] = []
    for j in range(valid.size):
        if not kept_local or np.all(np.abs(corr[j, kept_local]) <= threshold):
            kept_local.append(j)

    return valid[np.asarray(kept_local, dtype=int)].astype(int)


def fit_preprocessor(X_train: np.ndarray, feature_names: Sequence[str]) -> Tuple[Preprocessor, np.ndarray]:
    X_train = np.asarray(X_train, dtype=float)
    if not np.all(np.isfinite(X_train)):
        raise ValueError("Non-finite training feature encountered before preprocessing.")

    std0 = np.std(X_train, axis=0, ddof=0)
    keep_nonconstant = np.where(np.isfinite(std0) & (std0 > 0))[0]
    if keep_nonconstant.size == 0:
        raise ValueError("All features are zero/non-finite variance.")

    X1 = X_train[:, keep_nonconstant]
    mean_ = np.mean(X1, axis=0)
    std_ = np.std(X1, axis=0, ddof=0)
    if np.any(~np.isfinite(std_)) or np.any(std_ <= 0):
        raise ValueError("Invalid standard deviation after zero-variance filtering.")

    Xz = (X1 - mean_) / std_
    keep_spearman = greedy_spearman_keep(Xz, SPEARMAN_THRESHOLD)
    Xout = Xz[:, keep_spearman]

    return (
        Preprocessor(
            keep_nonconstant=keep_nonconstant,
            mean_=mean_,
            std_=std_,
            keep_spearman=keep_spearman,
            input_feature_names=list(feature_names),
        ),
        Xout,
    )


def apply_preprocessor(prep: Preprocessor, X: np.ndarray) -> np.ndarray:
    X = np.asarray(X, dtype=float)
    if not np.all(np.isfinite(X)):
        raise ValueError("Non-finite feature encountered before preprocessing.")

    X1 = X[:, prep.keep_nonconstant]
    Xz = (X1 - prep.mean_) / prep.std_
    Xout = Xz[:, prep.keep_spearman]

    if not np.all(np.isfinite(Xout)):
        raise ValueError("Non-finite feature encountered after preprocessing.")
    return Xout


def names_after_preprocessor(prep: Preprocessor) -> List[str]:
    after_nonconstant = [prep.input_feature_names[i] for i in prep.keep_nonconstant]
    return [after_nonconstant[i] for i in prep.keep_spearman]


