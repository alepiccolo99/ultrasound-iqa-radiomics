def parse_args() -> argparse.Namespace:
    script_path = Path(__file__).resolve()
    repo_root = script_path.parents[1]

    parser = argparse.ArgumentParser(
        description="Run reference-grouped nested model development on radiomic FR-IQA data."
    )
    parser.add_argument(
        "--input-mode",
        choices=["paper", "custom"],
        default="paper",
        help=(
            "Input source. 'paper' reproduces the study from exact public derived "
            "data; 'custom' reads radiomic_dataset.mat generated by the MATLAB "
            "wrapper plus a subjective-score CSV."
        ),
    )
    parser.add_argument(
        "--paper-data",
        type=Path,
        default=repo_root / "data" / "paper" / "paper_modeling_data.mat",
        help="Exact derived MAT file used for paper reproduction.",
    )
    parser.add_argument(
        "--custom-data",
        type=Path,
        default=repo_root / "data" / "user_input" / "radiomic_dataset.mat",
        help=(
            "Custom radiomic_dataset.mat generated by "
            "matlab/prepare_radiomic_dataset.m."
        ),
    )
    parser.add_argument(
        "--scores-file",
        type=Path,
        default=repo_root / "data" / "user_input" / "subjective_scores.csv",
        help=(
            "Custom CSV containing SampleID, ReferenceID, and SubjectiveTarget."
        ),
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=None,
        help=(
            "Directory in which analysis outputs are written. Defaults to "
            "results/ for paper mode and results/custom/ for custom mode."
        ),
    )
    return parser.parse_args()

def main() -> None:
    args = parse_args()
    start_time = time.time()

    if args.input_mode == "paper":
        X_ref, X_test, y, sample_id, group_index, feature_names, group_order = load_paper_dataset(
            args.paper_data.resolve()
        )
    else:
        X_ref, X_test, y, sample_id, group_index, feature_names, group_order = load_custom_dataset(
            args.custom_data.resolve(),
            args.scores_file.resolve(),
        )

    n_samples = len(y)
    n_groups = len(group_order)
    all_predictions = np.full(n_samples, np.nan, dtype=float)

    fold_metric_rows: List[Dict[str, Any]] = []
    selected_pipeline_rows: List[Dict[str, Any]] = []
    selected_feature_rows: List[Dict[str, Any]] = []

    print(f"Input mode: {args.input_mode}")
    print(f"Samples: {n_samples}")
    print(f"Reference groups: {n_groups}")
    print(f"Radiomic descriptors per image: {X_ref.shape[1]}")
    print(f"Candidate pipelines per outer fold: {len(REPRESENTATIONS) * len(LASSO_ALPHAS) * len(MODEL_CONFIGS)}")
    print(f"Master seed: {MASTER_SEED}\n")

    for outer_index, held_group in enumerate(group_order, start=1):
        fold_start = time.time()
        test_idx = np.where(group_index == outer_index)[0]
        train_idx = np.where(group_index != outer_index)[0]

        print(f"Outer fold {outer_index}/{n_groups}: held out {held_group}")
        print(f"  train={len(train_idx)} | test={len(test_idx)}")

        best = run_inner_search(
            outer_index=outer_index,
            outer_train_idx=train_idx,
            X_ref=X_ref,
            X_test=X_test,
            y=y,
            group_index=group_index,
            base_feature_names=feature_names,
        )

        pred, selected_names = fit_predict_outer(
            outer_index=outer_index,
            best=best,
            train_idx=train_idx,
            test_idx=test_idx,
            X_ref=X_ref,
            X_test=X_test,
            y=y,
            base_feature_names=feature_names,
        )

        all_predictions[test_idx] = pred
        metrics = regression_metrics(y[test_idx], pred)

        print(
            f"  selected: {best['Representation']} | LASSO={best['LassoAlpha']} | "
            f"{best['ModelFamily']} {best['ModelParamsJSON']} | features={len(selected_names)}"
        )
        print(
            f"  held-out RMSE={metrics['RMSE']:.6f} | R2={metrics['R2']:.6f} | "
            f"PLCC={metrics['PLCC']:.6f} | SROCC={metrics['SROCC']:.6f}"
        )
        print(f"  elapsed={((time.time() - fold_start) / 60):.1f} min\n")

        fold_metric_rows.append({
            "OuterFold": outer_index,
            "HeldOutReferenceID": held_group,
            "NTrain": len(train_idx),
            "NTest": len(test_idx),
            **metrics,
        })

        selected_pipeline_rows.append({
            "OuterFold": outer_index,
            "HeldOutReferenceID": held_group,
            "Representation": best["Representation"],
            "LassoAlpha": best["LassoAlpha"],
            "ModelFamily": best["ModelFamily"],
            "ModelParamsJSON": best["ModelParamsJSON"],
            "SelectedFeatureCount": len(selected_names),
            "InnerRMSE": best["InnerRMSE"],
            "InnerMAE": best["InnerMAE"],
            "InnerR2": best["InnerR2"],
        })

        for rank, name in enumerate(selected_names, start=1):
            selected_feature_rows.append({
                "OuterFold": outer_index,
                "HeldOutReferenceID": held_group,
                "SelectionRank": rank,
                "FeatureName": name,
            })

    if not np.all(np.isfinite(all_predictions)):
        raise RuntimeError("Some outer predictions were not generated.")

    aggregate = regression_metrics(y, all_predictions)

    if args.output_dir is None:
        repo_root = Path(__file__).resolve().parents[1]
        output_dir = (
            repo_root / "results"
            if args.input_mode == "paper"
            else repo_root / "results" / "custom"
        )
    else:
        output_dir = args.output_dir.resolve()

    output_dir.mkdir(parents=True, exist_ok=True)

    predictions = pd.DataFrame({
        "SampleID": sample_id,
        "ReferenceID": [group_order[i - 1] for i in group_index],
        "SubjectiveTarget": y,
        "OutOfReferencePrediction": all_predictions,
        "Residual": y - all_predictions,
    })
    predictions.to_csv(output_dir / "predictions.csv", index=False)
    pd.DataFrame(fold_metric_rows).to_csv(output_dir / "fold_metrics.csv", index=False)
    pd.DataFrame(selected_pipeline_rows).to_csv(output_dir / "selected_pipelines.csv", index=False)
    pd.DataFrame(selected_feature_rows).to_csv(output_dir / "selected_features.csv", index=False)

    versions = {
        "python": sys.version,
        "platform": platform.platform(),
        "numpy": np.__version__,
        "pandas": pd.__version__,
        "scipy": scipy.__version__,
        "scikit_learn": sklearn.__version__,
        "master_seed": MASTER_SEED,
    }
    (output_dir / "software_versions.json").write_text(
        json.dumps(versions, indent=2, sort_keys=True),
        encoding="utf-8",
    )

    summary = {
        "InputMode": args.input_mode,
        "N": n_samples,
        "ReferenceGroups": n_groups,
        "MAE": aggregate["MAE"],
        "RMSE": aggregate["RMSE"],
        "R2": aggregate["R2"],
        "PLCC": aggregate["PLCC"],
        "SROCC": aggregate["SROCC"],
        "MasterSeed": MASTER_SEED,
        "ElapsedMinutes": (time.time() - start_time) / 60.0,
    }
    (output_dir / "summary.json").write_text(
        json.dumps(summary, indent=2, sort_keys=True),
        encoding="utf-8",
    )

    print("Aggregate out-of-reference performance")
    print(f"  MAE   = {aggregate['MAE']:.8f}")
    print(f"  RMSE  = {aggregate['RMSE']:.8f}")
    print(f"  R2    = {aggregate['R2']:.8f}")
    print(f"  PLCC  = {aggregate['PLCC']:.8f}")
    print(f"  SROCC = {aggregate['SROCC']:.8f}")
    print(f"\nOutputs written to: {output_dir}")


if __name__ == "__main__":
    main()
