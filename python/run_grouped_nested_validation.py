def _matlab_cell_strings(value: np.ndarray) -> List[str]:
    """Convert a MATLAB cell/string array loaded by scipy.io.loadmat to Python strings."""
    arr = np.asarray(value)
    out: List[str] = []

    for item in arr.ravel(order="F"):
        if isinstance(item, str):
            out.append(item)
            continue

        if isinstance(item, bytes):
            out.append(item.decode("utf-8"))
            continue

        if isinstance(item, np.ndarray):
            squeezed = np.asarray(item).squeeze()

            if squeezed.ndim == 0:
                out.append(str(squeezed.item()))
                continue

            if squeezed.dtype.kind in {"U", "S"}:
                flat = squeezed.ravel(order="F").tolist()
                if len(flat) == 1:
                    out.append(str(flat[0]))
                else:
                    out.append("".join(str(x) for x in flat))
                continue

            if squeezed.size == 1:
                out.append(str(squeezed.item()))
                continue

        out.append(str(item))

    return out


def load_paper_dataset(paper_file: Path) -> Tuple[
    np.ndarray,
    np.ndarray,
    np.ndarray,
    np.ndarray,
    np.ndarray,
    List[str],
    List[str],
]:
    """Load exact derived numerical inputs used for paper reproduction."""
    if not paper_file.is_file():
        raise FileNotFoundError(f"Paper modeling data file not found: {paper_file}")

    data = loadmat(paper_file)

    required = {
        "X_reference",
        "X_test",
        "y",
        "sample_id",
        "group_index",
        "feature_names",
        "reference_labels",
    }
    missing = sorted(required.difference(data.keys()))
    if missing:
        raise ValueError(
            "paper_modeling_data.mat is missing required variable(s): "
            + ", ".join(missing)
        )

    X_reference = np.asfortranarray(np.asarray(data["X_reference"], dtype=float))
    X_test = np.asfortranarray(np.asarray(data["X_test"], dtype=float))
    y = np.asarray(data["y"], dtype=float).ravel(order="F")
    sample_id = np.asarray(data["sample_id"]).ravel(order="F")
    group_index = np.asarray(data["group_index"]).ravel(order="F").astype(int)

    feature_names = _matlab_cell_strings(data["feature_names"])
    group_order = _matlab_cell_strings(data["reference_labels"])

    if X_reference.ndim != 2 or X_test.ndim != 2:
        raise ValueError("X_reference and X_test must be 2-D matrices.")
    if X_test.shape[0] != y.size:
        raise ValueError("X_test row count must equal the number of targets.")
    if sample_id.size != y.size or group_index.size != y.size:
        raise ValueError("Sample/group identifiers must match the number of targets.")
    if X_reference.shape[1] != X_test.shape[1]:
        raise ValueError("Reference and test radiomic feature dimensions differ.")
    if X_test.shape[1] != len(feature_names):
        raise ValueError("Feature-name count does not match radiomic feature dimension.")
    if X_test.shape[1] != 280:
        raise ValueError("Expected exactly 280 radiomic descriptors per image.")
    if len(set(feature_names)) != len(feature_names):
        raise ValueError("Duplicate radiomic feature names found.")
    if len(group_order) != X_reference.shape[0]:
        raise ValueError("Reference-label count does not match X_reference rows.")
    if len(group_order) < 3:
        raise ValueError("Grouped nested validation requires at least three reference groups.")

    expected_groups = np.arange(1, len(group_order) + 1, dtype=int)
    observed_groups = np.unique(group_index)
    if not np.array_equal(observed_groups, expected_groups):
        raise ValueError(
            "group_index must contain consecutive one-based group IDs matching reference_labels."
        )

    if np.any(group_index < 1) or np.any(group_index > X_reference.shape[0]):
        raise ValueError("group_index contains an invalid reference-group index.")

    # Reconstruct the per-sample reference matrix from exact stored doubles.
    # Column-major layout matches scipy.io.loadmat behavior for the frozen MAT.
    X_ref = np.asfortranarray(X_reference[group_index - 1, :], dtype=float)

    if not (
        np.all(np.isfinite(X_ref))
        and np.all(np.isfinite(X_test))
        and np.all(np.isfinite(y))
    ):
        raise ValueError("Non-finite value found in paper modeling data.")

    return X_ref, X_test, y, sample_id, group_index, feature_names, group_order


def load_custom_dataset(
    radiomic_file: Path,
    scores_file: Path,
) -> Tuple[
    np.ndarray,
    np.ndarray,
    np.ndarray,
    np.ndarray,
    np.ndarray,
    List[str],
    List[str],
]:
    """Load a custom MATLAB radiomic dataset and align its subjective targets.

    ``radiomic_file`` must be generated by ``prepare_radiomic_dataset.m`` and
    contain exact reference/test radiomic doubles plus plain MATLAB metadata.
    ``scores_file`` must contain:
        SampleID, ReferenceID, SubjectiveTarget
    """
    if not radiomic_file.is_file():
        raise FileNotFoundError(f"Custom radiomic dataset not found: {radiomic_file}")
    if not scores_file.is_file():
        raise FileNotFoundError(f"Custom subjective-score file not found: {scores_file}")

    data = loadmat(radiomic_file)

    required = {
        "X_reference",
        "X_test",
        "sample_id",
        "group_index",
        "feature_names",
        "reference_labels",
    }
    missing = sorted(required.difference(data.keys()))
    if missing:
        raise ValueError(
            "Custom radiomic_dataset.mat is missing required variable(s): "
            + ", ".join(missing)
        )

    X_reference = np.asfortranarray(np.asarray(data["X_reference"], dtype=float))
    X_test = np.asfortranarray(np.asarray(data["X_test"], dtype=float))
    sample_ids = _matlab_cell_strings(data["sample_id"])
    group_index = np.asarray(data["group_index"]).ravel(order="F").astype(int)
    feature_names = _matlab_cell_strings(data["feature_names"])
    group_order = _matlab_cell_strings(data["reference_labels"])

    if X_reference.ndim != 2 or X_test.ndim != 2:
        raise ValueError("X_reference and X_test must be 2-D matrices.")
    if X_test.shape[0] != len(sample_ids):
        raise ValueError("X_test row count must equal the number of SampleID values.")
    if group_index.size != len(sample_ids):
        raise ValueError("group_index length must equal the number of test samples.")
    if X_reference.shape[1] != X_test.shape[1]:
        raise ValueError("Reference and test radiomic feature dimensions differ.")
    if X_test.shape[1] != len(feature_names):
        raise ValueError("Feature-name count does not match radiomic feature dimension.")
    if X_test.shape[1] != 280:
        raise ValueError(
            "Expected exactly 280 radiomic descriptors per image. "
            "Generate the custom dataset with prepare_radiomic_dataset.m."
        )
    if len(set(feature_names)) != len(feature_names):
        raise ValueError("Duplicate radiomic feature names found.")
    if len(group_order) != X_reference.shape[0]:
        raise ValueError("Reference-label count does not match X_reference rows.")
    if len(group_order) < 3:
        raise ValueError(
            "Grouped nested validation requires at least three reference groups."
        )
    if len(set(sample_ids)) != len(sample_ids):
        raise ValueError("SampleID values in radiomic_dataset.mat must be unique.")
    if len(set(group_order)) != len(group_order):
        raise ValueError("Reference labels in radiomic_dataset.mat must be unique.")

    expected_groups = np.arange(1, len(group_order) + 1, dtype=int)
    observed_groups = np.unique(group_index)
    if not np.array_equal(observed_groups, expected_groups):
        raise ValueError(
            "group_index must contain consecutive one-based group IDs matching "
            "reference_labels."
        )

    if np.any(group_index < 1) or np.any(group_index > X_reference.shape[0]):
        raise ValueError("group_index contains an invalid reference-group index.")

    scores = pd.read_csv(
        scores_file,
        dtype={"SampleID": str, "ReferenceID": str},
    )

    required_score_columns = {"SampleID", "ReferenceID", "SubjectiveTarget"}
    missing_score_columns = sorted(required_score_columns.difference(scores.columns))
    if missing_score_columns:
        raise ValueError(
            "Custom subjective-score CSV is missing required column(s): "
            + ", ".join(missing_score_columns)
        )

    scores = scores[["SampleID", "ReferenceID", "SubjectiveTarget"]].copy()
    scores["SampleID"] = scores["SampleID"].astype(str)
    scores["ReferenceID"] = scores["ReferenceID"].astype(str)

    if scores["SampleID"].duplicated().any():
        raise ValueError("SampleID values in the subjective-score CSV must be unique.")
    if scores["SampleID"].isna().any() or scores["ReferenceID"].isna().any():
        raise ValueError("Subjective-score CSV contains missing SampleID or ReferenceID.")

    score_sample_ids = set(scores["SampleID"])
    mat_sample_ids = set(sample_ids)

    missing_scores = sorted(mat_sample_ids - score_sample_ids)
    extra_scores = sorted(score_sample_ids - mat_sample_ids)

    if missing_scores:
        preview = ", ".join(missing_scores[:10])
        raise ValueError(
            f"Missing subjective targets for {len(missing_scores)} sample(s): {preview}"
        )
    if extra_scores:
        preview = ", ".join(extra_scores[:10])
        raise ValueError(
            f"Subjective-score CSV contains {len(extra_scores)} unknown sample(s): {preview}"
        )

    score_lookup = scores.set_index("SampleID")
    aligned_scores = score_lookup.loc[sample_ids]

    expected_reference_labels = np.asarray(
        [group_order[i - 1] for i in group_index],
        dtype=object,
    )
    observed_reference_labels = aligned_scores["ReferenceID"].astype(str).to_numpy()

    if not np.array_equal(expected_reference_labels, observed_reference_labels):
        mismatch = np.where(expected_reference_labels != observed_reference_labels)[0]
        i = int(mismatch[0])
        raise ValueError(
            "ReferenceID mismatch between radiomic_dataset.mat and subjective-score "
            f"CSV for SampleID '{sample_ids[i]}': expected "
            f"'{expected_reference_labels[i]}', found "
            f"'{observed_reference_labels[i]}'."
        )

    y = pd.to_numeric(
        aligned_scores["SubjectiveTarget"],
        errors="raise",
    ).to_numpy(dtype=float)

    # Reconstruct one reference feature vector per test sample from the exact
    # doubles stored by MATLAB. Keep column-major layout for numerical
    # consistency with the paper reproduction path.
    X_ref = np.asfortranarray(X_reference[group_index - 1, :], dtype=float)
    X_test = np.asfortranarray(X_test, dtype=float)

    if not (
        np.all(np.isfinite(X_ref))
        and np.all(np.isfinite(X_test))
        and np.all(np.isfinite(y))
    ):
        raise ValueError("Non-finite value found in custom modeling data.")

    sample_id = np.asarray(sample_ids, dtype=object)

    return X_ref, X_test, y, sample_id, group_index, feature_names, group_order


